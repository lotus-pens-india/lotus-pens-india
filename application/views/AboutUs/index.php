            <h3>The Barrel :</h3>
            <p>Barrel: the long part of the main body of the pen which houses the ink reservoir.
                Threads: thin grooves cut into a pen to hold parts together, especially pen caps
                to the pen body.
                Step: the part of the barrel where the threads 'step up' to the body, which can
                matter when holding the pen.
                Body: the length of a pen barrel that typically houses the ink reservoir.
                Trim Ring: ornamental accents that serve an aesthetic purpose.
            </p>
