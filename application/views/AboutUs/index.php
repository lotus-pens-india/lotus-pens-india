            <h3>The Cap:</h3>
            <p>Cap: the part of a pen that covers the nib and attaches to the pen body.
                Clip: the metal doohickey usually attached to the cap that holds your pen in your
                shirt pocket and also keeps it from rolling off your desk and landing nib first on
                the ground (why does it ALWAYS fall nib down??)
                Finial: the top of the cap, sometimes decorated with the maker's logo.
                Insert: the plastic liner on the inside of some pen caps that help seal the nib and
                keep it wet when capped.
                Centerband: the metal decorative ring that is usually placed near the bottom of
                the pen cap for decorative purposes, or perhaps to provide reinforcement to the
                cap threads.
                Lip: the open end of the cap, where the threads of the body fit to close the pen.
            </p>
