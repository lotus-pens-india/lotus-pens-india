            <h3>The Feed :</h3>
            <p>Feed: the piece of plastic or ebonite (usually black) that hugs the back of the nib and acts as
                a vehicle for ink delivery from the reservoir to the nib.
                Wings: the widest part of the feed that matches up to the nib shoulder. Sometimes nibs will
                slide on and grab onto the feed wings.
                Fins: the small, thin pieces on the feed that allow ink to saturate into the air channels. These
                act as an ink regulator for consistent flow when writing speed varies.
                Ink Channel: a very thin slit in the feed that hugs against the back of the nib and provides a
                route for the ink to travel through the feed. This is what helps to provide the necessary
                capillary action required for ink flow.
                Post: the back end of a feed that goes into the ink reservoir and feeds ink into the channel.
            </p>
