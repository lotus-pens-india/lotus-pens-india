            <h3>The Converter :</h3>
            <p>Converter: a small filling mechanism (usually a screw-piston type) that fits onto
                a pen that also accepts a cartridge. This allows you to use any brand's bottled ink
                instead of relying on limited proprietary ink cartridges.
                Mouth: the opening that fits onto the feed post to hold the converter in place.
                Ink Reservoir: a cavity inside a pen that holds ink.
                Seal: the 'working' part of the converter piston that creates a vacuum in order to
                draw ink into the reservoir.
                Rod: the threaded portion of the piston mechanism that causes the seal to move
                up and down when the knob is turned.
                Shroud: the metal covering that holds the piston mechanism onto the back of the
                ink reservoir.
                Knob: the part of the converter that you turn to move the piston seal up and down
                (and thus fill the converter).
            </p>
